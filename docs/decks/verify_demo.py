"""Verify the FlameScope demo deck with python-pptx (no renderer needed).

Checks: slide count, a title and speaker notes on every slide, headline length, every shape
inside the slide, a rough text-overflow estimate for text boxes and tables, a minimum font
size, image data present, and no AI or tool attribution in core properties, slide text or
notes, no application name in app properties. Run: `.venv/bin/python docs/decks/verify_demo.py`.
"""

from __future__ import annotations

import sys
from collections.abc import Iterator
from pathlib import Path

from pptx import Presentation
from pptx.enum.shapes import MSO_SHAPE_TYPE
from pptx.presentation import Presentation as PresentationType
from pptx.shapes.base import BaseShape
from pptx.slide import Slide
from pptx.util import Emu
from verify_pitch import (
    app_properties_problems,
    has_text,
    is_outside,
    lacks_image,
    overflows,
    word_count,
)

DECK_PATH = Path(__file__).resolve().parent / "flamescope-demo.pptx"
EXPECTED_SLIDES = 43
TITLE_SLIDE = 1
HEADLINE_WORD_LIMIT = 14
MIN_FONT_PT = 12.0
FOOTER_NAMES = frozenset({"footer", "slide-number"})
FOOTER_RULE_IN = 6.85
ATTRIBUTION_TERMS = ("claude", "anthropic", "openai", "chatgpt", "generated by", "co-authored")
METADATA_TERMS = (*ATTRIBUTION_TERMS, "python", "pptx")
AVERAGE_GLYPH_WIDTH_EM = 0.52
LINE_HEIGHT_EM = 1.2
POINTS_PER_INCH = 72
DEFAULT_CELL_PT = 14.0
CELL_PADDING_IN = 0.24


def text_runs(shape: BaseShape) -> Iterator[object]:
    if shape.has_text_frame:
        for paragraph in shape.text_frame.paragraphs:
            yield from paragraph.runs
    if shape.shape_type == MSO_SHAPE_TYPE.TABLE:
        for row in shape.table.rows:
            for cell in row.cells:
                for paragraph in cell.text_frame.paragraphs:
                    yield from paragraph.runs


def has_small_font(shape: BaseShape) -> bool:
    if shape.name in FOOTER_NAMES:
        return False
    return any(run.font.size and run.font.size.pt < MIN_FONT_PT for run in text_runs(shape))


def cell_height_in(cell: object, width_in: float) -> float:
    total_pt = 0.0
    for paragraph in cell.text_frame.paragraphs:  # type: ignore[attr-defined]
        sizes = [run.font.size.pt for run in paragraph.runs if run.font.size]
        size = max(sizes, default=DEFAULT_CELL_PT)
        usable_pt = max(1.0, (width_in - CELL_PADDING_IN) * POINTS_PER_INCH)
        chars_per_line = max(1, int(usable_pt / (size * AVERAGE_GLYPH_WIDTH_EM)))
        total_pt += max(1, -(-len(paragraph.text) // chars_per_line)) * size * LINE_HEIGHT_EM
    return total_pt / POINTS_PER_INCH + CELL_PADDING_IN / 2


def table_bottom_in(shape: BaseShape) -> float:
    table = shape.table
    widths = [Emu(column.width).inches for column in table.columns]
    height = 0.0
    for row in table.rows:
        estimated = max(
            cell_height_in(cell, width) for cell, width in zip(row.cells, widths, strict=True)
        )
        height += max(Emu(row.height).inches, estimated)
    return Emu(shape.top).inches + height


def table_overflows(shape: BaseShape) -> bool:
    return shape.shape_type == MSO_SHAPE_TYPE.TABLE and table_bottom_in(shape) > FOOTER_RULE_IN


SHAPE_CHECKS = (
    (is_outside, "extends beyond the slide"),
    (
        lambda shape, _deck: shape.shape_type != MSO_SHAPE_TYPE.TABLE and overflows(shape),
        "text likely overflows its box",
    ),
    (lambda shape, _deck: table_overflows(shape), "table likely runs into the footer"),
    (lambda shape, _deck: has_small_font(shape), f"has text under {MIN_FONT_PT:g} pt"),
    (lambda shape, _deck: lacks_image(shape), "has no image data"),
)


def shape_problems(slide: Slide, deck: PresentationType) -> list[str]:
    return [
        f"{shape.name} {message}"
        for shape in slide.shapes
        for check, message in SHAPE_CHECKS
        if check(shape, deck)
    ]


def slide_text(slide: Slide) -> str:
    texts = [shape.text_frame.text for shape in slide.shapes if has_text(shape)]
    notes = slide.notes_slide.notes_text_frame.text if slide.has_notes_slide else ""
    return " ".join([*texts, notes]).lower()


def content_problems(number: int, slide: Slide) -> list[str]:
    title = slide.shapes.title
    if title is None or not title.text_frame.text.strip():
        return ["missing title"]
    problems = []
    if number != TITLE_SLIDE and word_count(title.text_frame.text) > HEADLINE_WORD_LIMIT:
        problems.append(f"headline over {HEADLINE_WORD_LIMIT} words")
    if not slide.has_notes_slide or not slide.notes_slide.notes_text_frame.text.strip():
        problems.append("missing speaker notes")
    text = slide_text(slide)
    problems += [f"names {term!r}" for term in ATTRIBUTION_TERMS if term in text]
    return problems


def metadata_problems(deck: PresentationType) -> list[str]:
    properties = deck.core_properties
    fields = (
        properties.author,
        properties.last_modified_by,
        properties.title,
        properties.subject,
        properties.keywords,
        properties.comments,
        properties.category,
    )
    text = " ".join(field or "" for field in fields).lower()
    return [f"core properties name {term!r}" for term in METADATA_TERMS if term in text]


def verify_deck(path: Path, expected: int) -> list[str]:
    deck = Presentation(str(path))
    slides = list(deck.slides)
    problems = [] if len(slides) == expected else [f"{len(slides)} slides, not {expected}"]
    for number, slide in enumerate(slides, start=1):
        found = [*shape_problems(slide, deck), *content_problems(number, slide)]
        problems += [f"slide {number}: {problem}" for problem in found]
    return problems + metadata_problems(deck) + app_properties_problems(path)


def summary(path: Path) -> list[str]:
    deck = Presentation(str(path))
    return [
        f"{number:2d}. {slide.shapes.title.text_frame.text}"
        for number, slide in enumerate(deck.slides, start=1)
    ]


def main(path: Path = DECK_PATH, expected: int = EXPECTED_SLIDES) -> None:
    print("\n".join(summary(path)))
    problems = verify_deck(path, expected)
    if problems:
        sys.exit("verification failed:\n" + "\n".join(problems))
    print(f"{path.name}: {expected} slides verified")


if __name__ == "__main__":
    main()
